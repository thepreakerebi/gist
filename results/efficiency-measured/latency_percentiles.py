"""Tail latency (P50, P95, P99, max) from the committed timing records, checked against budgets.

`measured.md` reports medians only. A median says what a typical question costs;
it says nothing about the slow ones a user actually notices. This script reads
the raw per-call records already committed in this directory and reports the
tail, without re-running anything:

  efficiency_measurements.jsonl   RTX 4090 run: `select` (live scorers) and
                                  `answer` (Qwen2.5-Omni-7B fp16) per question
  cached_selection.jsonl          laptop CPU: per-video `ingest`, per-question
                                  `cached_s` and `live_s` selection

Percentiles use the nearest-rank method (the smallest sample with at least p% of
samples at or below it), so every reported figure is an observed latency, not an
interpolation. At n = 17 or 18, P95 and P99 are both the slowest or second-slowest
call. They are reported because the budget is stated as P95, not because 18
samples estimate a 99th percentile.

Warmup follows `measured.md`: the first successful answer call per condition is
dropped, since it pays one-off CUDA kernel compilation. Out-of-memory calls are
counted as errors, not as latencies. Cached and live selection keep every
question, matching the 1.26 s median quoted in the README.

The budgets below were set on 2026-11-06, after the run, from the use case: a
person waiting on a typed question in the web app. They were not pre-registered,
so a pass here is a check against a stated target, not a confirmatory test.

    python results/efficiency-measured/latency_percentiles.py
"""

from __future__ import annotations

import json
import math
from pathlib import Path

HERE = Path(__file__).resolve().parent

# Budget per measured quantity: (percentile, seconds, rationale).
BUDGETS: dict[str, tuple[int, float, str]] = {
    "select_cached": (95, 3.0, "the path the web app runs for each question"),
    "answer_gist": (95, 2.0, "answer stage on the selected evidence, RTX 4090 fp16"),
    "ingest": (95, 300.0, "one-off per video, before the first question, in the background"),
}
ERROR_BUDGET = 0.01  # share of calls allowed to fail (out of memory) per condition


def nearest_rank(values: list[float], p: float) -> float:
    ordered = sorted(values)
    rank = max(1, math.ceil(p / 100 * len(ordered)))
    return ordered[rank - 1]


def summarise(values: list[float]) -> dict[str, float]:
    return {
        "n": len(values),
        "p50": nearest_rank(values, 50),
        "p95": nearest_rank(values, 95),
        "p99": nearest_rank(values, 99),
        "max": max(values),
    }


def load(name: str) -> list[dict]:
    return [json.loads(line) for line in (HERE / name).read_text().splitlines() if line.strip()]


def collect() -> tuple[dict[str, list[float]], dict[str, tuple[int, int]]]:
    """Return latencies per series and (errors, attempts) per GPU condition."""
    series: dict[str, list[float]] = {}
    errors: dict[str, tuple[int, int]] = {}
    seen_warmup: set[str] = set()

    for rec in load("efficiency_measurements.jsonl"):
        if rec.get("record") != "stage":
            continue
        cond = (rec.get("extra") or {}).get("condition", "?")
        key = f"{rec['stage']}_{cond}"
        failed, total = errors.get(key, (0, 0))
        errors[key] = (failed + bool(rec["oom"] or rec["error"]), total + 1)
        if rec["oom"] or rec["error"]:
            continue
        if rec["stage"] == "answer" and key not in seen_warmup:
            seen_warmup.add(key)
            continue
        name = key if rec["stage"] == "answer" else "select_live_gpu"
        series.setdefault(name, []).append(rec["wall_seconds"])

    for rec in load("cached_selection.jsonl"):
        if rec.get("record") == "ingest":
            series.setdefault("ingest", []).append(rec["ingest_s"])
        elif rec.get("record") == "question":
            series.setdefault("select_cached", []).append(rec["cached_s"])
            series.setdefault("select_live_cpu", []).append(rec["live_s"])
    return series, errors


LABELS = {
    "select_cached": "Selection, cached embeddings (laptop CPU)",
    "select_live_cpu": "Selection, live scorers (laptop CPU)",
    "select_live_gpu": "Selection, live scorers (RTX 4090 run)",
    "answer_full": "Answer, uniform 8 frames (RTX 4090)",
    "answer_gist": "Answer, Gist-selected evidence (RTX 4090)",
    "ingest": "Ingest, once per video (laptop CPU)",
}

HEADER = """\
# Tail latency and budgets

Generated by `latency_percentiles.py` from the committed records in this directory.
Nearest-rank percentiles; at n of 18 or fewer, P95 and P99 are the slowest calls,
not estimates.

| Quantity | n | P50 s | P95 s | P99 s | Max s | Budget | Result |
| :-- | --: | --: | --: | --: | --: | :-- | :-- |"""

ERRORS_HEADER = """
## Error rate (RTX 4090 run)

Budget: at most {budget:.0%} of calls fail per condition. Failures here are
out-of-memory errors.

| Stage and condition | Failed | Attempts | Rate | Result |
| :-- | --: | --: | --: | :-- |"""

BUDGETS_HEADER = """
## Budgets

Set on 2026-11-06, after the run, for a person waiting on a typed question.
Not pre-registered.
"""

# Observations on the two budget failures, read from the raw records. Kept as text
# rather than computed because the explanations come from the error strings and
# question order, not from the numbers.
FOOTER = """
## Failures against budget

- **Cached selection, P95 9.18 s against 3 s.** One question, 870-3, took 9.18 s;
  the next slowest took 3.31 s and fifteen of eighteen finished within 3 s. 870-3
  was the third question on its video, not a first call, so model warm-up does not
  explain it. It ran on a laptop CPU with other processes live, and the run did not
  record CPU load, so the cause is not established. A repeat on an idle machine
  would settle it.
- **Answer stage, Gist, 1 of 18 out of memory.** Question 869-2. The CUDA error
  text records a second process holding 3.76 GiB on the same card, so the 24 GB
  was shared at that moment. The uniform arm hit no error in the same session. The
  failure is recorded as it happened and is not excluded from the rate.

The P50 here (1.18 s) differs from the 1.26 s median in the README because
nearest-rank takes an observed sample, while the README median averages the two
middle samples of 18.

## What this does not show

- Throughput or behaviour under concurrent users. Every call here ran alone.
- The hosted answering model in the web app (TwelveLabs Pegasus). Its latency is
  outside Gist and is not measured here.
- A P99 in the statistical sense. Eighteen samples cannot estimate one.
"""


def render(series: dict[str, list[float]], errors: dict[str, tuple[int, int]]) -> str:
    lines = [HEADER]
    for key, label in LABELS.items():
        if key not in series:
            continue
        s = summarise(series[key])
        if key in BUDGETS:
            pct, limit, _ = BUDGETS[key]
            budget = f"P{pct} ≤ {limit:g} s"
            result = "pass" if s[f"p{pct}"] <= limit else "**fail**"
        else:
            budget, result = "none", "reported only"
        cells = [label, str(s["n"])]
        cells += [f"{s[k]:.2f}" for k in ("p50", "p95", "p99", "max")]
        cells += [budget, result]
        lines.append("| " + " | ".join(cells) + " |")

    lines.append(ERRORS_HEADER.format(budget=ERROR_BUDGET))
    for key, (failed, total) in sorted(errors.items()):
        rate = failed / total
        result = "pass" if rate <= ERROR_BUDGET else "**fail**"
        lines.append(f"| {key} | {failed} | {total} | {rate:.1%} | {result} |")

    lines.append(BUDGETS_HEADER)
    for key, (pct, limit, why) in BUDGETS.items():
        lines.append(f"- **{LABELS[key]}**: P{pct} ≤ {limit:g} s, {why}.")
    lines.append(FOOTER)
    return "\n".join(lines)


def main() -> None:
    series, errors = collect()
    out = render(series, errors)
    (HERE / "latency.md").write_text(out)
    print(out)


if __name__ == "__main__":
    main()
